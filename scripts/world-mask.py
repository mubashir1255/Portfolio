"""Build src/data/world-mask.ts: a low-res land/water grid for the hero globe.

Source: Natural Earth 1:110m land (public domain), e.g.
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Usage: python3 scripts/world-mask.py ne_110m_land.geojson > src/data/world-mask.ts
Each row is one latitude band (north to south), packed as hex: 1 bit per cell, 1 = land.
"""
import json
import sys
from PIL import Image, ImageDraw

W, H = 144, 72  # 2.5 degrees per cell


def main(path: str) -> None:
    data = json.load(open(path))
    scale = 8  # draw large, then shrink, so thin land isn't lost
    img = Image.new("L", (W * scale, H * scale), 0)
    draw = ImageDraw.Draw(img)
    to_px = lambda lon, lat: ((lon + 180) / 360 * W * scale, (90 - lat) / 180 * H * scale)
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            draw.polygon([to_px(*pt[:2]) for pt in poly[0]], fill=255)
            for hole in poly[1:]:
                draw.polygon([to_px(*pt[:2]) for pt in hole], fill=0)
    small = img.resize((W, H), Image.BOX)
    px = small.load()
    rows = []
    for y in range(H):
        bits = "".join("1" if px[x, y] > 70 else "0" for x in range(W))
        rows.append(f"{int(bits, 2):0{W // 4}x}")
    print("/** Generated by scripts/world-mask.py from Natural Earth 1:110m land (public domain). Do not edit. */")
    print(f"export const MASK_W = {W};")
    print(f"export const MASK_H = {H};")
    print("/** One hex string per latitude band, north to south; 1 bit per cell (1 = land). */")
    print("export const WORLD_MASK = [")
    for r in rows:
        print(f"  '{r}',")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
